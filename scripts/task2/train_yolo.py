#!/usr/bin/env python3
"""Train a YOLO detector for CATHACTION Task 2 collision detection."""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import torch


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--model",
        default="yolo11n.yaml",
        help=(
            "Ultralytics model name/path. Use a .yaml model for no-download smoke "
            "tests, or a public .pt checkpoint such as yolo11s.pt for real training."
        ),
    )
    parser.add_argument(
        "--data",
        type=Path,
        default=Path("configs/task2/collision_detection_clean_combined.local.yaml"),
        help="YOLO dataset YAML generated by scripts/task2/prepare_yolo_splits.py.",
    )
    parser.add_argument("--epochs", type=int, default=3)
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--batch", default="16", help="Batch size, fraction, or 'auto'.")
    parser.add_argument("--workers", type=int, default=8)
    parser.add_argument(
        "--device",
        default="auto",
        help="Ultralytics device value. 'auto' uses 0 when CUDA is visible, otherwise cpu.",
    )
    parser.add_argument("--project", type=Path, default=Path("outputs/task2/yolo"))
    parser.add_argument("--name", default="yolo11n_640_smoke")
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--patience", type=int, default=30)
    parser.add_argument("--close-mosaic", type=int, default=10)
    parser.add_argument("--fraction", type=float, default=1.0)
    parser.add_argument("--val", default=True, action=argparse.BooleanOptionalAction)
    parser.add_argument("--cache", default=False, action=argparse.BooleanOptionalAction)
    parser.add_argument("--plots", default=True, action=argparse.BooleanOptionalAction)
    parser.add_argument("--resume", default=False, action=argparse.BooleanOptionalAction)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    repo_root = Path.cwd()
    data_yaml = args.data if args.data.is_absolute() else repo_root / args.data
    project = args.project if args.project.is_absolute() else repo_root / args.project

    os.environ.setdefault("YOLO_CONFIG_DIR", (repo_root / "outputs/task2/_ultralytics_config").as_posix())
    os.environ.setdefault("MPLCONFIGDIR", (repo_root / "outputs/task2/_mplconfig").as_posix())
    os.environ.setdefault("WANDB_DISABLED", "true")
    Path(os.environ["YOLO_CONFIG_DIR"]).mkdir(parents=True, exist_ok=True)
    Path(os.environ["MPLCONFIGDIR"]).mkdir(parents=True, exist_ok=True)
    project.mkdir(parents=True, exist_ok=True)

    device = args.device
    if device == "auto":
        device = "0" if torch.cuda.is_available() else "cpu"

    print(f"model={args.model}")
    print(f"data={data_yaml}")
    batch = parse_batch_arg(args.batch)

    print(f"epochs={args.epochs} imgsz={args.imgsz} batch={batch}")
    print(f"device={device} cuda_available={torch.cuda.is_available()} cuda={torch.version.cuda}")
    print(f"project={project} name={args.name}")

    from ultralytics import YOLO

    model = YOLO(args.model)
    model.train(
        data=data_yaml.as_posix(),
        epochs=args.epochs,
        imgsz=args.imgsz,
        batch=batch,
        workers=args.workers,
        device=device,
        project=project.as_posix(),
        name=args.name,
        seed=args.seed,
        patience=args.patience,
        close_mosaic=args.close_mosaic,
        fraction=args.fraction,
        val=args.val,
        cache=args.cache,
        plots=args.plots,
        resume=args.resume,
    )
    return 0


def parse_batch_arg(value: str) -> int | float:
    if value.lower() == "auto":
        return -1
    if "." in value:
        return float(value)
    return int(value)


if __name__ == "__main__":
    raise SystemExit(main())
